from ultralytics import YOLO

if __name__ == '__main__':
    # Загружаем чистую предобученную модель (без ваших предыдущих дообучений)
    model = YOLO("yolo26n.pt")

    # Запускаем обучение с оптимизированными параметрами
    model.train(
        data="dataset/data.yaml",   # путь к вашему датасету

        # Основные параметры
        epochs=150,                 # больше эпох + EarlyStopping остановит при отсутствии прогресса
        batch=8,                    # если видеокарта позволяет, можно 16 (больше стабильность градиента)
        imgsz=640,                  # лучше для мелких объектов (слизни могут быть маленькими)
        device=0,                   # GPU 0; если нет GPU, ставьте 'cpu'
        workers=4,                  # потоки для загрузки данных (0 было слишком медленно)
        amp=True,                   # автоматическая смешанная точность — ускоряет обучение

        # Регуляризация и оптимизатор
        optimizer='AdamW',          # часто лучше SGD для небольших датасетов
        lr0=0.001,                  # начальная скорость обучения (у AdamW чуть ниже, чем у SGD)
        lrf=0.01,                   # финальный lr = lr0 * lrf
        weight_decay=0.0005,        # для борьбы с переобучением
        momentum=0.937,             # для AdamW не сильно важен, но оставим дефолт

        # Аугментации (ключевое улучшение для слизней)
        hsv_h=0.02,                 # изменение оттенка
        hsv_s=0.7,                  # насыщенность
        hsv_v=0.4,                  # яркость
        degrees=15,                 # поворот на ±15°
        translate=0.1,              # сдвиг по x/y
        scale=0.5,                  # масштабирование от 0.5 до 1.5
        shear=5,                    # наклон
        perspective=0.0,            # нет перспективы (редко нужно)
        flipud=0.3,                 # отражение сверху/вниз – слизни могут быть перевернуты
        fliplr=0.5,                 # отражение влево/вправо
        mosaic=1.0,                 # мозаика из 4 фото – сильный приём для маленьких объектов
        mixup=0.2,                  # смешивание двух изображений
        copy_paste=0.3,             # полезно, если слизней мало – вставка объектов на разные фоны

        # Управление процессом
        single_cls=True,            # только один класс (слизни)
        patience=15,                # остановка, если метрика не растёт 15 эпох
        save_period=10,             # сохранять модель каждые 10 эпох (на всякий случай)
        plots=True,                 # генерировать графики (results.png и др.)
        exist_ok=False,             # если папка runs/train/train существует – не перезаписывать, а создать train2 и т.д.
    )

    print("\n✅ Обучение завершено. Лучшая модель сохранена в runs/train/.../weights/best.pt")